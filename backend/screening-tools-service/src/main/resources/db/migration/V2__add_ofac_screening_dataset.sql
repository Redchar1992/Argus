CREATE TABLE screening_dataset (
    provider_id     VARCHAR(64) PRIMARY KEY,
    source_uri      VARCHAR(1024) NOT NULL,
    published_on    DATE NOT NULL,
    fetched_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    sha256          VARCHAR(64) NOT NULL,
    entry_count     INTEGER NOT NULL,
    dataset_version VARCHAR(96) NOT NULL
);

CREATE TABLE ofac_sdn_address (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    normalized_address VARCHAR(256) NOT NULL,
    display_address    VARCHAR(256) NOT NULL,
    asset              VARCHAR(24) NOT NULL,
    entity             VARCHAR(500) NOT NULL,
    program            VARCHAR(500) NOT NULL,
    profile_id         VARCHAR(64) NOT NULL,
    dataset_version    VARCHAR(96) NOT NULL,
    CONSTRAINT uk_ofac_asset_address_profile
        UNIQUE (asset, normalized_address, profile_id)
);

CREATE INDEX idx_ofac_normalized_address ON ofac_sdn_address(normalized_address);
